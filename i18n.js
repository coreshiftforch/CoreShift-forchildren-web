  let lang = sessionStorage.getItem('coreshift-lang') || 'jp';

  function apply(l) {
    lang = l;
    sessionStorage.setItem('coreshift-lang', l);

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const k = el.dataset.i18n;
      if (T[l]?.[k] !== undefined) el.textContent = T[l][k];
    });

    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const k = el.dataset.i18nHtml;
      if (T[l]?.[k] !== undefined) el.innerHTML = T[l][k];
    });

    document.querySelectorAll('[data-i18n-alt]').forEach(el => {
      const k = el.dataset.i18nAlt;
      if (T[l]?.[k] !== undefined) el.alt = T[l][k];
    });

    document.documentElement.lang = l === 'en' ? 'en' : 'ja';

    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.toggle('lang-active', btn.textContent.trim().toLowerCase() === l);
    });
  }

  document.addEventListener('DOMContentLoaded', () => {
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.addEventListener('click', () => apply(btn.textContent.trim().toLowerCase()));
    });
    apply(lang);
  });
